"""Build the two-arm URDFs the 3D viewer shows for a bimanual robot.

Two copies of a single-arm URDF, every link and joint prefixed with ``left_`` /
``right_`` (matching the bimanual observation keys), mounted on a shared
``world`` link ``spacing`` metres apart and both facing +x. Mesh paths are left
untouched, so each output sits next to the URDF it was generated from.

    python scripts/make_bimanual_urdf.py
"""

import copy
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

PUBLIC = Path(__file__).resolve().parent.parent / "frontend" / "public"


@dataclass(frozen=True)
class Model:
    source: Path
    # Distance between the two arm bases. Purely visual: a follower has no
    # notion of where the other arm is.
    spacing_m: float

    @property
    def output(self) -> Path:
        return self.source.with_name(f"{self.source.stem}-bimanual.urdf")


MODELS = [
    Model(PUBLIC / "dk1-urdf" / "TRLC-DK1-Follower.urdf", 0.5),
    Model(PUBLIC / "so-101-urdf" / "urdf" / "so101_new_calib.urdf", 0.4),
]


def _prefixed_arm(arm: ET.Element, prefix: str) -> list[ET.Element]:
    """One arm's elements, renamed so two copies can share a document.

    Only direct children of <robot> are renamed: links, joints (with their
    parent/child/mimic references) and transmissions, which name the joints they
    drive. <material> definitions are shared and emitted once by the caller.
    """
    out: list[ET.Element] = []
    for element in arm:
        if element.tag == "material":
            continue
        element = copy.deepcopy(element)
        if element.tag == "link":
            element.set("name", prefix + element.get("name"))
        elif element.tag == "joint":
            element.set("name", prefix + element.get("name"))
            for tag in ("parent", "child"):
                ref = element.find(tag)
                ref.set("link", prefix + ref.get("link"))
            mimic = element.find("mimic")
            if mimic is not None:
                mimic.set("joint", prefix + mimic.get("joint"))
        elif element.tag == "transmission":
            if element.get("name"):
                element.set("name", prefix + element.get("name"))
            for inner in element.iter():
                if inner.tag in ("joint", "actuator") and inner.get("name"):
                    inner.set("name", prefix + inner.get("name"))
        out.append(element)
    return out


def _root_link(robot: ET.Element) -> str:
    """The link no joint declares as a child."""
    links = [link.get("name") for link in robot.findall("link")]
    children = {joint.find("child").get("link") for joint in robot.findall("joint")}

    roots = [name for name in links if name not in children]
    if len(roots) != 1:
        raise ValueError(f"expected exactly one root link, found {roots}")
    return roots[0]


def build(model: Model) -> None:
    source = ET.parse(model.source).getroot()
    root_link = _root_link(source)
    robot = ET.Element("robot", name=f"{source.get('name')}-bimanual")
    ET.SubElement(robot, "link", name="world")
    robot.extend(copy.deepcopy(m) for m in source.findall("material"))
    for prefix, y in (("left_", model.spacing_m / 2), ("right_", -model.spacing_m / 2)):
        robot.extend(_prefixed_arm(source, prefix))
        mount = ET.SubElement(robot, "joint", name=f"{prefix}mount", type="fixed")
        ET.SubElement(mount, "parent", link="world")
        ET.SubElement(mount, "child", link=f"{prefix}{root_link}")
        ET.SubElement(mount, "origin", xyz=f"0 {y} 0", rpy="0 0 0")
    ET.indent(robot)
    model.output.write_text(
        "<?xml version='1.0' encoding='utf-8'?>\n"
        f"<!-- Generated by scripts/{Path(__file__).name} from {model.source.name}; do not edit. -->\n"
        + ET.tostring(robot, encoding="unicode")
        + "\n"
    )
    print(f"Wrote {model.output.relative_to(PUBLIC.parent.parent)}")


def main() -> None:
    for model in MODELS:
        build(model)


if __name__ == "__main__":
    main()
