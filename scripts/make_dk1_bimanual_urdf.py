"""Build the two-arm DK1 URDF the 3D viewer shows for a bimanual robot.

Two copies of the single-arm follower URDF, every link and joint prefixed with
``left_`` / ``right_`` (matching the bimanual observation keys), mounted on a
shared ``world`` link ``ARM_SPACING_M`` apart, both facing +x. Mesh paths are
left untouched, so the output must sit next to the single-arm URDF.

    python scripts/make_dk1_bimanual_urdf.py
"""

import copy
import xml.etree.ElementTree as ET
from pathlib import Path

URDF_DIR = Path(__file__).resolve().parent.parent / "frontend" / "public" / "dk1-urdf"
SOURCE = URDF_DIR / "TRLC-DK1-Follower.urdf"
OUTPUT = URDF_DIR / "TRLC-DK1-Follower-bimanual.urdf"

# Distance between the two arm bases. Purely visual: the follower has no notion
# of where the other arm is.
ARM_SPACING_M = 0.5


def _prefixed_arm(arm: ET.Element, prefix: str) -> list[ET.Element]:
    arm = copy.deepcopy(arm)
    for link in arm.iter("link"):
        link.set("name", prefix + link.get("name"))
    for joint in arm.iter("joint"):
        joint.set("name", prefix + joint.get("name"))
        for tag in ("parent", "child"):
            ref = joint.find(tag)
            ref.set("link", prefix + ref.get("link"))
        mimic = joint.find("mimic")
        if mimic is not None:
            mimic.set("joint", prefix + mimic.get("joint"))
    return list(arm)


def main() -> None:
    source = ET.parse(SOURCE).getroot()
    robot = ET.Element("robot", name="TRLC-DK1-Follower-bimanual")
    ET.SubElement(robot, "link", name="world")
    for prefix, y in (("left_", ARM_SPACING_M / 2), ("right_", -ARM_SPACING_M / 2)):
        robot.extend(_prefixed_arm(source, prefix))
        mount = ET.SubElement(robot, "joint", name=f"{prefix}mount", type="fixed")
        ET.SubElement(mount, "parent", link="world")
        ET.SubElement(mount, "child", link=f"{prefix}base_link")
        ET.SubElement(mount, "origin", xyz=f"0 {y} 0", rpy="0 0 0")
    ET.indent(robot)
    OUTPUT.write_text(
        "<?xml version='1.0' encoding='utf-8'?>\n"
        f"<!-- Generated by scripts/{Path(__file__).name} from {SOURCE.name}; do not edit. -->\n"
        + ET.tostring(robot, encoding="unicode")
        + "\n"
    )
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
